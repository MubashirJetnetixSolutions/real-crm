// In-memory store for custom (user-added) properties
let customProperties: PropertyData[] = [];

export function getCustomProperties(): PropertyData[] {
  return customProperties;
}

export function saveCustomProperty(prop: PropertyData): void {
  customProperties = [prop, ...customProperties];
}

export function getPropertyById(id: string): PropertyData | undefined {
  const custom = customProperties.find((p) => p.id === id);
  if (custom) return custom;
  return properties.find((p) => p.id === id);
}

export function getPropertyGallery(property: PropertyData): string[] {
  if (property.gallery && property.gallery.length > 0) {
    return property.gallery;
  }
  return [property.imageUrl];
}

